"""
scripts/evaluate_real_world_pilot.py
-------------------------------------
Evaluates the frozen hybrid engine against the real-world Reddit pilot:
  data/trigger_model_check_validation_pilot.csv

This file contains 104 real Reddit mental-health sentences extracted from
both_train.csv / both_val.csv / both_test.csv (ADHD, anxiety, bipolar,
depression, PTSD subreddits).

IMPORTANT LIMITATIONS — read before interpreting results:
  1. Labels are WEAK — generated by lexical keyword rules, not human review.
  2. ZERO NONE examples — the pilot only contains trigger-positive candidates.
     NONE detection and false-positive rates CANNOT be measured here.
  3. Selection bias — sentences were selected *because* they matched trigger
     keywords. This inflates recall and deflates false-positive estimates.
  4. Reddit class ≠ trigger label — "adhd" source does not mean the sentence
     expresses an EXECUTIVE trigger. Many labels may be wrong.
  5. Do NOT use these numbers as proof of real-world performance.

What this DOES tell you:
  - How the engine behaves on real, unedited user-written text.
  - Which sentences it misses or over-triggers on.
  - Error patterns in raw natural language vs. the controlled benchmark.
"""

from __future__ import annotations

import csv
import sys
from pathlib import Path
from collections import defaultdict

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from app.hybrid_engine import HybridEngine  # noqa: E402

PILOT_PATH = PROJECT_ROOT / "data" / "trigger_model_check_validation_pilot.csv"
RESULTS_PATH = PROJECT_ROOT / "data" / "real_world_pilot_results.csv"
VALID_CATEGORIES = {"SENSORY", "EXECUTIVE", "SOCIAL_MASKING"}


def parse_gold(raw: str) -> frozenset[str]:
    parts = {p.strip().upper() for p in raw.split("|") if p.strip()}
    if parts == {"NONE"}:
        return frozenset()
    return frozenset(parts & VALID_CATEGORIES)


def prediction_from(result: dict) -> frozenset[str]:
    return frozenset(
        (set(result.get("detected_categories", []))
         | set(result.get("possible_categories", [])))
        & VALID_CATEGORIES
    )


def prf(tp, fp, fn):
    p = tp / (tp + fp) if tp + fp else 0.0
    r = tp / (tp + fn) if tp + fn else 0.0
    f1 = 2 * p * r / (p + r) if p + r else 0.0
    return p, r, f1


def main():
    if not PILOT_PATH.exists():
        print(f"ERROR: {PILOT_PATH} not found.", file=sys.stderr)
        sys.exit(1)

    with PILOT_PATH.open("r", encoding="utf-8", newline="") as fh:
        rows = list(csv.DictReader(fh))

    print(f"Loaded {len(rows)} pilot examples (real Reddit text, weak labels).")
    engine = HybridEngine()

    counters = {cat: {"tp": 0, "fp": 0, "fn": 0} for cat in VALID_CATEGORIES}
    exact_matches = 0
    per_example = []

    # Error analysis buckets
    fp_examples = []
    fn_examples = []

    for row in rows:
        gold = parse_gold(row.get("label", ""))
        result = engine.analyze(row["text"])
        predicted = prediction_from(result)

        exact = (gold == predicted)
        if exact:
            exact_matches += 1

        for cat in VALID_CATEGORIES:
            in_g, in_p = cat in gold, cat in predicted
            if in_g and in_p:
                counters[cat]["tp"] += 1
            elif not in_g and in_p:
                counters[cat]["fp"] += 1
                fp_examples.append((cat, row["text"], row.get("label",""), row.get("source_class","")))
            elif in_g and not in_p:
                counters[cat]["fn"] += 1
                fn_examples.append((cat, row["text"], row.get("label",""), row.get("source_class","")))

        kw_str = "; ".join(
            f"{t['phrase']}({t['category']})"
            for t in result.get("keyword_triggers", [])
        )
        per_example.append({
            "text": row["text"],
            "gold_label": row.get("label", ""),
            "predicted_label": "|".join(sorted(predicted)) if predicted else "NONE",
            "source_class": row.get("source_class", ""),
            "exact_match": str(exact),
            "tp": len(gold & predicted),
            "fp": len(predicted - gold),
            "fn": len(gold - predicted),
            "semantic_scores": str(result.get("semantic_scores", {})),
            "keyword_triggers": kw_str,
        })

    total = len(rows)
    print("\n" + "=" * 65)
    print("REAL-WORLD PILOT RESULTS  (weak labels — see limitations above)")
    print("=" * 65)
    print(f"Total examples  : {total}")
    print(f"Exact-match acc : {exact_matches}/{total} ({exact_matches/total:.1%})")
    print(f"\n{'NOTE':>6}: This pilot has NO NONE examples. Precision is inflated,")
    print(f"        NONE detection cannot be measured here.")

    print("\n--- Per-Category Metrics ---")
    macro_p = macro_r = macro_f1 = 0.0
    micro_tp = micro_fp = micro_fn = 0

    for cat in sorted(VALID_CATEGORIES):
        tp = counters[cat]["tp"]
        fp = counters[cat]["fp"]
        fn = counters[cat]["fn"]
        p, r, f1 = prf(tp, fp, fn)
        macro_p += p; macro_r += r; macro_f1 += f1
        micro_tp += tp; micro_fp += fp; micro_fn += fn
        print(f"  {cat:<20}  P={p:.3f}  R={r:.3f}  F1={f1:.3f}  "
              f"(TP={tp} FP={fp} FN={fn})")

    n = len(VALID_CATEGORIES)
    print(f"\n  {'Macro average':<20}  P={macro_p/n:.3f}  R={macro_r/n:.3f}  F1={macro_f1/n:.3f}")
    mp, mr, mf = prf(micro_tp, micro_fp, micro_fn)
    print(f"  {'Micro average':<20}  P={mp:.3f}  R={mr:.3f}  F1={mf:.3f}")
    print(f"\n  Total FP : {micro_fp}    Total FN (missed) : {micro_fn}")

    # Sample false positives
    print("\n--- Sample False Positives (engine fired, gold said otherwise) ---")
    for cat, text, gold_lbl, src in fp_examples[:8]:
        print(f"  [{cat}] src={src}  gold={gold_lbl}")
        print(f"    \"{text[:110]}...\"" if len(text) > 110 else f"    \"{text}\"")

    # Sample false negatives
    print("\n--- Sample False Negatives (engine missed, gold expected it) ---")
    for cat, text, gold_lbl, src in fn_examples[:8]:
        print(f"  [{cat}] src={src}  gold={gold_lbl}")
        print(f"    \"{text[:110]}...\"" if len(text) > 110 else f"    \"{text}\"")

    print("\n" + "=" * 65)
    print("LIMITATIONS REMINDER")
    print("=" * 65)
    print("  - Labels are auto-generated keywords heuristics, NOT ground truth.")
    print("  - No NONE examples — false-positive rate vs. neutral text unknown.")
    print("  - Selection bias inflates recall estimates.")
    print("  - Reddit source class (adhd/depression/etc) != trigger category.")
    print("  - These numbers CANNOT be compared to clinical or deployment needs.")

    # Save results
    fields = ["text","gold_label","predicted_label","source_class",
              "exact_match","tp","fp","fn","semantic_scores","keyword_triggers"]
    with RESULTS_PATH.open("w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=fields)
        w.writeheader()
        w.writerows(per_example)

    print(f"\nPer-example results saved to: {RESULTS_PATH}")


if __name__ == "__main__":
    main()
